package org.maiwithu.maidroid.runtime

import android.content.Context
import android.net.ConnectivityManager

/**
 * 容器的 DNS 配置。proot 里没有 Android 的 DNS 解析服务，容器里的 apt、git、uv 都直接向 resolv.conf 里的服务器查询。
 *
 * 手机当前网络下发的 DNS（运营商、路由器、校园网）排在最前，公共 DNS 只作兜底：
 * 有些网络会拦截公共 DNS，以前只写公共 DNS 时，这类网络下容器里的下载全部失败，重试也没用。
 */
internal object ContainerDns {
    /** 阿里、114、Google、Cloudflare。 */
    val PUBLIC_SERVERS = listOf("223.5.5.5", "114.114.114.114", "8.8.8.8", "1.1.1.1")

    // 只放行由十六进制数字、点和冒号组成的地址，地址最终要写进脚本里的配置文件。
    private val PLAIN_ADDRESS = Regex("[0-9A-Fa-f.:]+")

    /** 手机当前默认网络的 DNS 服务器地址；没有网络或读不到时返回空表。 */
    fun systemServers(context: Context): List<String> = runCatching {
        val connectivity = context.getSystemService(ConnectivityManager::class.java)
        val network = connectivity.activeNetwork ?: return@runCatching emptyList()
        connectivity.getLinkProperties(network)?.dnsServers.orEmpty().mapNotNull { it.hostAddress }
    }.getOrDefault(emptyList())

    /**
     * 生成 resolv.conf 正文：系统 DNS 在前、公共 DNS 在后，去重。
     * 带网卡后缀的 IPv6 链路本地地址（fe80::1%wlan0）glibc 不一定认，直接丢掉。
     * glibc 只用前三个 nameserver，且按顺序尝试（不加 rotate），系统 DNS 能用时就不会去碰公共 DNS。
     */
    fun resolvConf(systemServers: List<String>): String {
        val usableSystemServers = systemServers
            .map { it.trim() }
            .filter { it.matches(PLAIN_ADDRESS) && !it.startsWith("fe80", ignoreCase = true) }
        val nameservers = (usableSystemServers + PUBLIC_SERVERS).distinct()
        return buildString {
            appendLine("# Generated by MaiDroid OOBE.")
            nameservers.forEach { appendLine("nameserver $it") }
            appendLine("options timeout:2 attempts:2")
        }
    }
}
