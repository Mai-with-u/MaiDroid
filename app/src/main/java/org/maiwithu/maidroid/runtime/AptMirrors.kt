package org.maiwithu.maidroid.runtime

import org.maiwithu.maidroid.diagnostics.AUTO_FIX_LOG_PREFIX

/** 一个 Debian 软件源：显示名和 http 根地址，根地址下有 debian 和 debian-security 两个目录。 */
internal data class AptMirror(val name: String, val baseUrl: String)

/**
 * 容器里 apt 的软件源列表和换源重试。
 *
 * OOBE“配置容器”先写入第一个（清华）；之后装软件时下载失败（连不上、超时、索引校验不过、镜像正在同步），
 * 就按列表顺序换下一个、清掉旧索引重来，换成功的那个留在 sources.list 里，之后的 apt（例如装 sshd）都用它。
 * 空间满、手机时间不对这类换源也没用的失败不换，直接报错，交给错误码那边提示用户。
 *
 * 容器脚本的用法：把 shellFunctions() 拼在脚本最前面，之后调用
 * `maidroid_apt_write_sources <根地址>` 或 `maidroid_apt_install <软件包...>`。
 */
internal object AptMirrors {
    // 都用 http：rootfs 刚解包时还没装 CA 证书，https 源连不上；软件包本身有 apt 的签名校验。
    val ALL: List<AptMirror> = listOf(
        AptMirror("清华镜像", "http://mirrors.tuna.tsinghua.edu.cn"),
        AptMirror("中科大镜像", "http://mirrors.ustc.edu.cn"),
        AptMirror("阿里云镜像", "http://mirrors.aliyun.com"),
        AptMirror("Debian 官方源", "http://deb.debian.org")
    )

    /** OOBE 默认写入的源。 */
    val DEFAULT: AptMirror get() = ALL.first()

    /** 所有源的显示名，用于“都试过了”的失败说明。 */
    val allNames: String get() = ALL.joinToString("、") { it.name }

    // 这些输出说明是下载出了问题，换一个源有希望；排除掉的几种（空间满、时间不对）换源也一样失败。
    private const val FETCH_FAILED_PATTERN =
        "Failed to fetch|Unable to fetch|Some index files failed|Hash Sum mismatch|File has unexpected size|" +
            "Mirror sync in progress|Temporary failure resolving|Could not resolve|Could not connect|" +
            "Connection failed|Connection timed out|Unable to connect"
    private const val NOT_MIRROR_PATTERN = "No space left on device|is not valid yet|invalid since"

    /**
     * 定义换源用的 shell 函数。maidroid_apt_install 失败返回 1 时，maidroid_apt_failed_step 记着失败在哪一步：
     * update（更新索引）、install（安装）或 mirrors（下载失败、所有源都试过了）。
     */
    fun shellFunctions(): String {
        val bases = ALL.joinToString(" ") { shellQuote(it.baseUrl) }
        val nameCases = ALL.joinToString("\n") { "        ${shellQuote(it.baseUrl)}) printf '%s' ${shellQuote(it.name)} ;;" }
        return listOf(
            """
            maidroid_apt_mirror_bases() {
                printf '%s\n' $bases
            }

            maidroid_apt_mirror_name() {
                case "${'$'}1" in
            """.trimIndent(),
            nameCases,
            """
                    *) printf '%s' "${'$'}1" ;;
                esac
            }

            # 按 rootfs 的发行版代号写 sources.list：主仓库、updates 和 security 三行，都指向同一个源。
            maidroid_apt_write_sources() {
                apt_base="${'$'}1"
                apt_codename="${'$'}(. /etc/os-release 2>/dev/null; printf '%s' "${'$'}{VERSION_CODENAME:-}")"
                [ -n "${'$'}apt_codename" ] || apt_codename=bookworm
                printf '%s\n' \
                    "# Generated by MaiDroid." \
                    "deb ${'$'}apt_base/debian ${'$'}apt_codename main contrib" \
                    "deb ${'$'}apt_base/debian ${'$'}apt_codename-updates main contrib" \
                    "deb ${'$'}apt_base/debian-security ${'$'}apt_codename-security main contrib" \
                    > /etc/apt/sources.list
            }

            # apt 的网络设置：失败重试三次、不用管线（有些镜像不支持）、连接或下载 30 秒没动静就算失败。
            # 默认要等 120 秒，下载到一半断网时会卡很久；NapCat 安装器自己调的 apt-get 也读这份配置。
            maidroid_apt_write_network_conf() {
                mkdir -p /etc/apt/apt.conf.d
                printf '%s\n' 'Acquire::Retries "3";' 'Acquire::http::Pipeline-Depth "0";' 'Acquire::http::Timeout "30";' \
                    > /etc/apt/apt.conf.d/99maidroid-network
            }

            # 换源后清掉旧源的索引和半下载的文件，免得混着用。
            maidroid_apt_reset_lists() {
                apt-get clean
                rm -rf /var/lib/apt/lists/*
                mkdir -p /var/lib/apt/lists/partial
            }

            maidroid_apt_current_base() {
                sed -n 's#^deb \(https\{0,1\}://[^/ ]*\)/debian .*#\1#p' /etc/apt/sources.list 2>/dev/null | head -n 1
            }

            # 跑一条 apt-get：输出照常打到终端，同时留一份，失败后据此判断要不要换源。
            maidroid_apt_run() {
                { "${'$'}@"; echo "${'$'}?" > /tmp/maidroid-apt.status; } 2>&1 | tee /tmp/maidroid-apt.log
                return "${'$'}(cat /tmp/maidroid-apt.status 2>/dev/null || echo 1)"
            }

            # 上一条 apt-get 是不是因为下载失败：是才值得换源。
            maidroid_apt_fetch_failed() {
                if grep -qiE '$NOT_MIRROR_PATTERN' /tmp/maidroid-apt.log 2>/dev/null; then
                    return 1
                fi
                grep -qiE '$FETCH_FAILED_PATTERN' /tmp/maidroid-apt.log 2>/dev/null
            }

            # 更新索引 -> 安装；下载失败就换下一个源、清掉旧索引重来，直到成功或所有源都试过。
            # 连接或下载 30 秒没动静就算失败（apt 默认等 120 秒、还要重试三次）：下载到一半断网时，
            # 四个源挨个等满要半个多小时，界面一直停在“正在安装”；改成 30 秒，断网几分钟内就报出来、可以自动重试。
            maidroid_apt_install() {
                apt_current="${'$'}(maidroid_apt_current_base)"
                apt_tried=" ${'$'}apt_current "
                while :; do
                    if ! maidroid_apt_run apt-get -o Acquire::http::Pipeline-Depth=0 -o Acquire::http::Timeout=30 --error-on=any update; then
                        maidroid_apt_failed_step=update
                    elif ! maidroid_apt_run apt-get -o Acquire::http::Timeout=30 install -y -f --no-install-recommends "${'$'}@"; then
                        maidroid_apt_failed_step=install
                    else
                        return 0
                    fi
                    maidroid_apt_fetch_failed || return 1
                    apt_next=""
                    for apt_base in ${'$'}(maidroid_apt_mirror_bases); do
                        case "${'$'}apt_tried" in
                            *" ${'$'}apt_base "*) ;;
                            *) apt_next="${'$'}apt_base"; break ;;
                        esac
                    done
                    if [ -z "${'$'}apt_next" ]; then
                        maidroid_apt_failed_step=mirrors
                        return 1
                    fi
                    printf "$AUTO_FIX_LOG_PREFIX %s下载失败，换成%s重试\n" \
                        "${'$'}(maidroid_apt_mirror_name "${'$'}apt_current")" "${'$'}(maidroid_apt_mirror_name "${'$'}apt_next")"
                    maidroid_apt_write_sources "${'$'}apt_next"
                    maidroid_apt_reset_lists
                    apt_current="${'$'}apt_next"
                    apt_tried="${'$'}apt_tried${'$'}apt_next "
                done
            }
            """.trimIndent()
        ).joinToString("\n")
    }
}
